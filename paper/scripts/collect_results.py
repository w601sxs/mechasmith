"""Collect the paper's Table 1 from the bundled designs' build reports.

Run from the repository root:

    uv run python paper/scripts/collect_results.py            # read existing build/<name>/report.json
    uv run python paper/scripts/collect_results.py --rebuild  # rebuild every design first

On a headless machine the rebuild needs an X server for the renders:
    MUJOCO_GL=glfw xvfb-run -a -s "-screen 0 1280x1024x24" uv run python paper/scripts/collect_results.py --rebuild

Writes paper/generated/results.json (raw numbers) and paper/generated/table_designs.tex.
Every number in Table 1 comes from here; do not type numbers into the paper by hand.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "paper" / "generated"

# name, kind, reference mass in grams (None: no independent reference), source of that mass.
# G1's per-link masses are the reference's by construction (mass budgets), so its total is not
# a fidelity result and is left out of the comparison column.
DESIGNS = [
    ("so101", "arm", 632.0, "SO-ARM100 MJCF"),
    ("robotiq_2f85", "gripper", 1053.0, "Menagerie robotiq_2f85"),
    ("crazyflie2", "quadrotor", 27.0, "Menagerie bitcraze_crazyflie_2"),
    ("microduck", "biped", 737.0, "Pollen Microduck MJCF"),
    ("microduck_jetpack", "biped + fans", None, "no reference (new design)"),
    ("go2", "quadruped", 15210.0, "Menagerie unitree_go2"),
    ("g1", "humanoid", None, "masses are budgets from Menagerie unitree_g1"),
    ("duck_leg", "leg", None, "no reference"),
]


def rebuild(name: str) -> None:
    cmd = ["uv", "run", "mechasmith", "build", name]
    res = subprocess.run(cmd, cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True)
    if res.returncode != 0:
        sys.exit(f"build {name} failed:\n{res.stderr[-2000:]}")


def summarise(name: str, kind: str, ref_g: float | None, ref_src: str) -> dict:
    r = json.loads((ROOT / "build" / name / "report.json").read_text())
    joints = r["interference"]["joints"]
    full = sum(1 for j in joints.values() if j["usable"] == j["declared"])
    loc = sum(1 for line in (ROOT / "designs" / f"{name}.py").read_text().splitlines()
              if line.strip() and not line.strip().startswith("#"))
    test = None
    for key, ok in (("stand", "stands"), ("hover", "hovers"), ("arm", "holds")):
        if key in r:
            test = {"kind": key, "pass": bool(r[key][ok]),
                    **{k: v for k, v in r[key].items() if isinstance(v, (int, float, str, bool))}}
    mass = r["mass"]["total_g"]
    return {
        "design": name, "kind": kind, "loc": loc,
        "mass_g": mass, "ref_mass_g": ref_g, "ref_source": ref_src,
        "mass_err_pct": None if ref_g is None else 100.0 * (mass - ref_g) / ref_g,
        "home_collisions": len(r["interference"]["home_collisions"]),
        "swept_joints": len(joints), "full_range_joints": full,
        "test": test, "build_s": r["timing_s"]["total"],
    }


def fmt_mass(g: float) -> str:
    return f"{g / 1000:.2f}\\,kg" if g >= 5000 else f"{g:.1f}\\,g"


def table(rows: list[dict]) -> str:
    lines = [
        "% Generated by paper/scripts/collect_results.py. Do not edit by hand.",
        "\\begin{tabular}{llrrrcrl}",
        "\\toprule",
        "Design & Type & LoC & Mass & $\\Delta m$ & Coll. & Full range & Test \\\\",
        "\\midrule",
    ]
    for x in rows:
        dm = "--" if x["mass_err_pct"] is None else f"{x['mass_err_pct']:+.1f}\\%"
        rng = f"{x['full_range_joints']}/{x['swept_joints']}" if x["swept_joints"] else "--"
        t = x["test"]
        test = "--" if t is None else f"{t['kind']}: {'pass' if t['pass'] else 'fail'}"
        name = x["design"].replace("_", "\\_")
        lines.append(f"\\texttt{{{name}}} & {x['kind']} & {x['loc']} & {fmt_mass(x['mass_g'])} & {dm} "
                     f"& {x['home_collisions']} & {rng} & {test} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rebuild", action="store_true")
    args = ap.parse_args()
    rows = []
    for name, kind, ref_g, src in DESIGNS:
        if args.rebuild:
            rebuild(name)
        rows.append(summarise(name, kind, ref_g, src))
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "results.json").write_text(json.dumps(rows, indent=2) + "\n")
    (OUT / "table_designs.tex").write_text(table(rows))
    print(json.dumps(rows, indent=2))


if __name__ == "__main__":
    main()
