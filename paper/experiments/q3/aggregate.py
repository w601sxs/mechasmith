"""Aggregate Q3 results into paper/generated/q3.json and paper/generated/table_q3.tex.

    python aggregate.py [--results results/]

For each model (correct, or one fault at one severity) and DR setting: the mean over seeds of the
fall rate and forward-speed error on the model it was trained on and on the correct model. The
gap between the two is the cost of the fault that training could not see.
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
GEN = HERE.parents[1] / "generated"
UNITS = {"axis_tilt": "deg", "anchor_shift": "mm", "com_shift": "mm", "mass_scale": "x", "foot_offset": "mm"}
LABEL = {"axis_tilt": "knee axis tilted", "anchor_shift": "knee joint moved", "com_shift": "head CoM moved",
         "mass_scale": "trunk mass scaled", "foot_offset": "foot contact moved"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, default=HERE / "results")
    a = ap.parse_args()
    groups = defaultdict(list)
    for p in sorted(a.results.glob("*.json")):
        r = json.loads(p.read_text())
        f = r["fault"]
        key = ("clean", "", 0.0) if f is None else (f["kind"], f["target"], f["severity"])
        groups[(key, r["dr"])].append(r)
    rows = []
    for (key, dr), rs in sorted(groups.items(), key=lambda kv: (kv[0][1], kv[0][0][0] != "clean", kv[0][0])):
        def m(where, metric):
            v = [x[where]["summary"][metric] for x in rs]
            return float(np.mean(v)), float(np.std(v))
        rows.append({"model": key[0], "target": key[1], "severity": key[2], "dr": dr, "seeds": len(rs),
                     **{f"{w}_{k}": m(w, k) for w in ("on_train_model", "on_correct_model")
                        for k in ("fall_rate", "speed_err")}})
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "q3.json").write_text(json.dumps(rows, indent=2) + "\n")
    lines = ["% Generated by paper/experiments/q3/aggregate.py. Do not edit by hand.",
             "\\begin{tabular}{lrcrrrr}", "\\toprule",
             "& & & \\multicolumn{2}{c}{Fall rate} & \\multicolumn{2}{c}{Speed error (m/s)} \\\\",
             "\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
             "Fault & Severity & DR & trained & correct & trained & correct \\\\", "\\midrule"]
    for r in rows:
        label = "none (correct model)" if r["model"] == "clean" else LABEL[r["model"]]
        sev = "--" if r["model"] == "clean" else f"{r['severity']:g}\\,{UNITS[r['model']]}"
        f = lambda t: f"{t[0]:.2f}"
        lines.append(f"{label} & {sev} & {'yes' if r['dr'] else 'no'} & {f(r['on_train_model_fall_rate'])} & "
                     f"{f(r['on_correct_model_fall_rate'])} & {f(r['on_train_model_speed_err'])} & "
                     f"{f(r['on_correct_model_speed_err'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    (GEN / "table_q3.tex").write_text("\n".join(lines))
    print(f"{len(rows)} rows from {sum(len(v) for v in groups.values())} runs")


if __name__ == "__main__":
    main()
